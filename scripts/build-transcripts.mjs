// Turns the hand-authored transcripts in data/transcripts/*.txt into typed
// modules in data/generated/*.ts. Every line gets a stable id, a start and an
// end time (seconds). Times come from word count at a natural speaking rate,
// then are scaled to the "# target:" duration when one is given.
//
// Raw format:
//   # id: flagship            meeting id (required)
//   # target: 3655            optional total duration in seconds
//   # offset: 3               optional seconds of silence before the first line
//   speaker: text {#anchor}   one line of speech; anchor is optional
//   [pause 4]                 extra silence before the next line
//   A line ending in "—" is cut off: the next line starts before it would end.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "data/transcripts");
const outDir = join(root, "data/generated");
mkdirSync(outDir, { recursive: true });

const WORDS_PER_SEC = 2.6;

// Small deterministic jitter so gaps don't look machine-uniform.
function jitter(seed) {
  let h = 2166136261;
  for (const c of seed) h = Math.imul(h ^ c.charCodeAt(0), 16777619);
  return ((h >>> 0) % 1000) / 1000 - 0.5;
}

const round1 = (n) => Math.round(n * 10) / 10;

for (const file of readdirSync(srcDir).filter((f) => f.endsWith(".txt"))) {
  const raw = readFileSync(join(srcDir, file), "utf8").split("\n");
  const meta = {};
  const parsed = [];
  let pendingPause = 0;

  raw.forEach((line, i) => {
    const t = line.trim();
    if (!t) return;
    const m = t.match(/^#\s*(\w+):\s*(.+)$/);
    if (m) return void (meta[m[1]] = m[2].trim());
    if (t.startsWith("#")) return;
    const p = t.match(/^\[pause\s+([\d.]+)\]$/);
    if (p) return void (pendingPause += Number(p[1]));
    const s = t.match(/^([a-z]+):\s+(.+)$/);
    if (!s) throw new Error(`${file}:${i + 1}: cannot parse "${t}"`);
    let text = s[2];
    let anchor;
    const a = text.match(/\s*\{#([a-zA-Z0-9_]+)\}\s*$/);
    if (a) {
      anchor = a[1];
      text = text.slice(0, a.index).trim();
    }
    parsed.push({ speaker: s[1], text, anchor, pause: pendingPause });
    pendingPause = 0;
  });

  if (!meta.id) throw new Error(`${file}: missing "# id:"`);
  const offset = Number(meta.offset ?? 2);

  // Natural timing.
  let t = offset;
  const timed = parsed.map((l, i) => {
    const words = l.text.split(/\s+/).length;
    const dur = Math.max(0.7, words / WORDS_PER_SEC) * (1 + jitter(l.text) * 0.15);
    const prev = parsed[i - 1];
    if (prev) {
      const cutOff = prev.text.endsWith("—");
      const gap = cutOff ? -0.4 : prev.speaker === l.speaker ? 0.25 : 0.6 + jitter(l.text + i) * 0.5;
      t += gap + l.pause;
    }
    const start = t;
    t += dur;
    return { ...l, start, end: t };
  });

  // Scale to target duration, keeping the leading offset fixed.
  const naturalEnd = timed[timed.length - 1].end;
  const target = meta.target ? Number(meta.target) : naturalEnd;
  const k = (target - offset) / (naturalEnd - offset);
  const lines = timed.map((l, i) => ({
    id: `L${String(i + 1).padStart(3, "0")}`,
    speaker: l.speaker,
    text: l.text,
    start: round1(offset + (l.start - offset) * k),
    end: round1(offset + (l.end - offset) * k),
    anchor: l.anchor,
  }));
  // A cut-off line ends where the interrupter starts.
  for (let i = 0; i < lines.length - 1; i++) {
    if (lines[i].end > lines[i + 1].start) lines[i].end = lines[i + 1].start;
  }

  const anchors = {};
  for (const l of lines) {
    if (!l.anchor) continue;
    if (anchors[l.anchor]) throw new Error(`${file}: duplicate anchor ${l.anchor}`);
    anchors[l.anchor] = l.id;
  }

  const name = meta.id.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
  const out =
    `// GENERATED by scripts/build-transcripts.mjs from data/transcripts/${file}. Do not edit by hand.\n` +
    `import type { Line } from "../types";\n\n` +
    `export const ${name}Anchors = ${JSON.stringify(anchors, null, 2)} as const;\n\n` +
    `export const ${name}Lines: Line[] = [\n` +
    lines
      .map((l) => `  ${JSON.stringify({ id: l.id, speaker: l.speaker, text: l.text, start: l.start, end: l.end })},`)
      .join("\n") +
    `\n];\n`;
  writeFileSync(join(outDir, `${meta.id}.ts`), out);
  const wpm = Math.round(
    (lines.reduce((n, l) => n + l.text.split(/\s+/).length, 0) /
      lines.reduce((n, l) => n + (l.end - l.start), 0)) * 60,
  );
  console.log(
    `${meta.id}: ${lines.length} lines, ${Math.floor(target / 60)}m${Math.round(target % 60)}s, ` +
      `${Object.keys(anchors).length} anchors, ~${wpm} wpm while speaking`,
  );
}
